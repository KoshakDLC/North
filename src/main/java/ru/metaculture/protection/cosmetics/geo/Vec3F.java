package ru.metaculture.protection.cosmetics.geo;

public final class Vec3F {
   public float x;
   public float y;
   public float z;

   public Vec3F(float x, float y, float z) {
      this.x = x;
      this.y = y;
      this.z = z;
   }

   public float getX() {
      return this.x;
   }

   public float getY() {
      return this.y;
   }

   public float getZ() {
      return this.z;
   }
}
